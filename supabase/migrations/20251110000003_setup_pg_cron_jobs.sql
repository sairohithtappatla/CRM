-- Create a view to monitor cron jobs
CREATE OR REPLACE VIEW public.cron_job_status AS
SELECT
  jobid,
  schedule,
  command,
  nodename,
  nodeport,
  database,
  username,
  active,
  jobname
FROM cron.job
WHERE database = current_database()
ORDER BY jobname;

COMMENT ON VIEW public.cron_job_status IS 'Monitor status of all scheduled cron jobs';

-- Create function to get cron job history
CREATE OR REPLACE FUNCTION public.get_cron_job_history(
  job_name_filter text DEFAULT NULL,
  limit_rows int DEFAULT 50
)
RETURNS TABLE (
  jobid bigint,
  runid bigint,
  job_name text,
  status text,
  return_message text,
  start_time timestamp with time zone,
  end_time timestamp with time zone,
  duration interval
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  RETURN QUERY
  SELECT
    jh.jobid,
    jh.runid,
    j.jobname,
    jh.status,
    jh.return_message,
    jh.start_time,
    jh.end_time,
    (jh.end_time - jh.start_time) as duration
  FROM cron.job_run_details jh
  JOIN cron.job j ON jh.jobid = j.jobid
  WHERE
    (job_name_filter IS NULL OR j.jobname = job_name_filter)
    AND j.database = current_database()
  ORDER BY jh.start_time DESC
  LIMIT limit_rows;
END;
$$;

COMMENT ON FUNCTION public.get_cron_job_history IS 'Get execution history of cron jobs';

-- Create a table to log custom job executions
CREATE TABLE public.cron_execution_log (
  id uuid NOT NULL DEFAULT uuid_generate_v4(),
  job_name text NOT NULL,
  executed_at timestamp with time zone DEFAULT now(),
  status text NOT NULL CHECK (status = ANY (ARRAY['success'::text, 'failed'::text, 'partial'::text])),
  details jsonb DEFAULT '{}'::jsonb,
  error_message text,
  duration_ms bigint,
  CONSTRAINT cron_execution_log_pkey PRIMARY KEY (id)
);

CREATE INDEX idx_cron_execution_log_job_name ON public.cron_execution_log(job_name);
CREATE INDEX idx_cron_execution_log_executed_at ON public.cron_execution_log(executed_at);

-- Enable RLS
ALTER TABLE public.cron_execution_log ENABLE ROW LEVEL SECURITY;

CREATE POLICY cron_log_all ON public.cron_execution_log
FOR ALL
TO public
USING (true)
WITH CHECK (true);

COMMENT ON TABLE public.cron_execution_log IS 'Custom log table for tracking cron job executions and their results';

